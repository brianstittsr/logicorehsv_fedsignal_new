async function generateDocxNarrative(workspace: any): Promise<Buffer> {
  if (!Docx) {
    return Buffer.from(workspace.projectNarrative || "No narrative provided");
  }

  const {
    Document,
    Paragraph,
    TextRun,
    HeadingLevel,
    AlignmentType,
    Packer,
  } = Docx;

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          new Paragraph({
            text: workspace.sf424?.projectTitle || workspace.title || "Project Narrative",
            heading: HeadingLevel.TITLE,
            alignment: AlignmentType.CENTER,
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `Agency: ${workspace.agency || "N/A"}`,
                bold: true,
              }),
            ],
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `Solicitation: ${workspace.solicitationNumber || "N/A"}`,
                bold: true,
              }),
            ],
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `Budget: $${parseFloat(workspace.budgetSummary?.totalCosts || "0").toLocaleString()}`,
                bold: true,
              }),
            ],
          }),
          new Paragraph({
            text: "",
          }),
          new Paragraph({
            text: "PROJECT NARRATIVE",
            heading: HeadingLevel.HEADING_1,
          }),
          new Paragraph({
            text: workspace.projectNarrative || "No project narrative provided.",
          }),
          new Paragraph({
            text: "",
          }),
          new Paragraph({
            text: "ABSTRACT",
            heading: HeadingLevel.HEADING_1,
          }),
          new Paragraph({
            text: workspace.abstract || "No abstract provided.",
          }),
          new Paragraph({
            text: "",
          }),
          new Paragraph({
            text: "KEY PERSONNEL",
            heading: HeadingLevel.HEADING_1,
          }),
          ...(workspace.keyPersonnel?.length
            ? workspace.keyPersonnel.map((person: string) => new Paragraph({ text: `• ${person}` }))
            : [new Paragraph({ text: "No key personnel listed." })]),
        ],
      },
    ],
  });

  const buffer = await Packer.toBuffer(doc);
  return buffer;
}

function generateBudgetContent(workspace: any): string {
  const bs = workspace.budgetSummary || {};
  return `Budget Summary
Generated by FedSignal

Direct Costs,${parseFloat(bs.directCosts || "0").toFixed(2)}
Indirect Costs (F&A @ 55%),${parseFloat(bs.indirectCosts || "0").toFixed(2)}
TOTAL PROJECT COST,${parseFloat(bs.totalCosts || "0").toFixed(2)}

Note: F&A rate calculated at 55%. Adjust as per your institution's negotiated rate.
`;
}

function generateXlsxBudget(workspace: any): Buffer {
  if (!XLSX) {
    return Buffer.from(generateBudgetContent(workspace));
  }

  const bs = workspace.budgetSummary || {};
  const data = [
    ["FedSignal Budget Summary"],
    ["Generated:", new Date().toLocaleDateString()],
    [],
    ["Category", "Amount"],
    ["Direct Costs", parseFloat(bs.directCosts || "0")],
    ["Indirect Costs (F&A @ 55%)", parseFloat(bs.indirectCosts || "0")],
    ["TOTAL PROJECT COST", parseFloat(bs.totalCosts || "0")],
    [],
    ["Opportunity:", workspace.title || "N/A"],
    ["Agency:", workspace.agency || "N/A"],
    ["Solicitation:", workspace.solicitationNumber || "N/A"],
  ];

  const ws = XLSX.utils.aoa_to_sheet(data);
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, ws, "Budget Summary");

  return XLSX.write(wb, { type: "buffer", bookType: "xlsx" });
}

function generateChecklistContent(workspace: any): string {
  const checklist = workspace.checklist || {};
  const items = [
    { id: "sf424-complete", label: "SF-424 form completed" },
    { id: "narrative-draft", label: "Project narrative drafted" },
    { id: "budget-complete", label: "Budget summary with F&A calculated" },
    { id: "personnel-confirmed", label: "Key personnel bios attached" },
    { id: "budget-totals-match", label: "Budget totals match narrative" },
    { id: "deadline-valid", label: "Deadline not passed" },
    { id: "hbcu-eligible", label: "HBCU set-aside eligibility confirmed" },
    { id: "subk-plan", label: "Sub-contracting plan (if required)" },
  ];

  return `
================================================================================
                    FEDSIGNAL COMPLIANCE CHECKLIST
================================================================================

Generated: ${new Date().toLocaleString()}
Opportunity: ${workspace.title || "N/A"}
Agency: ${workspace.agency || "N/A"}

--------------------------------------------------------------------------------
CHECKLIST ITEMS
--------------------------------------------------------------------------------

${items
  .map((item) => `[${checklist[item.id] ? "X" : " "}] ${item.label}`)
  .join("\n")}

--------------------------------------------------------------------------------
STATUS SUMMARY
--------------------------------------------------------------------------------

Required Items Passed: ${items.filter((i) => i.id !== "hbcu-eligible" && i.id !== "subk-plan" && checklist[i.id]).length} / 6
Optional Items Passed: ${items.filter((i) => (i.id === "hbcu-eligible" || i.id === "subk-plan") && checklist[i.id]).length} / 2

Overall Status: ${items.filter((i) => i.id !== "hbcu-eligible" && i.id !== "subk-plan").every((i) => checklist[i.id]) ? "READY FOR SUBMISSION" : "INCOMPLETE - DO NOT SUBMIT"}

================================================================================
                              END OF CHECKLIST
================================================================================
`.trim();
}

