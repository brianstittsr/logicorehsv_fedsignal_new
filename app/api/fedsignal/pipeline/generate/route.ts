import { NextRequest, NextResponse } from "next/server";
import JSZip from "jszip";

// Optional imports - will use fallback if not available
let Docx: any;
let PDFDocument: any;
let XLSX: any;

try {
  Docx = require("docx");
} catch {
  console.log("docx package not available, using text fallback");
}

try {
  XLSX = require("xlsx");
} catch {
  console.log("xlsx package not available, using CSV fallback");
}

export async function POST(request: NextRequest) {
  try {
    const { workspace } = await request.json();

    if (!workspace) {
      return NextResponse.json({ error: "No workspace data provided" }, { status: 400 });
    }

    const zip = new JSZip();

    // Generate SF-424 PDF (or text fallback)
    const sf424Content = generateSF424Content(workspace);
    zip.file("SF-424.txt", sf424Content);

    // Generate Project Narrative DOCX (or text fallback)
    if (Docx) {
      const narrativeBuffer = await generateDocxNarrative(workspace);
      zip.file("Project_Narrative.docx", narrativeBuffer);
    } else {
      zip.file("Project_Narrative.txt", workspace.projectNarrative || "No narrative provided");
    }

    // Generate Budget XLSX (or CSV fallback)
    const budgetContent = generateBudgetContent(workspace);
    if (XLSX) {
      const budgetBuffer = generateXlsxBudget(workspace);
      zip.file("Budget_Summary.xlsx", budgetBuffer);
    } else {
      zip.file("Budget_Summary.csv", budgetContent);
    }

    // Generate Compliance Checklist
    const checklistContent = generateChecklistContent(workspace);
    zip.file("Compliance_Checklist.txt", checklistContent);

    // Generate README
    const readme = generateReadme(workspace);
    zip.file("README.txt", readme);

    const zipArrayBuffer = await zip.generateAsync({ type: "arraybuffer" });

    return new NextResponse(zipArrayBuffer, {
      status: 200,
      headers: {
        "Content-Type": "application/zip",
        "Content-Disposition": `attachment; filename="fedsignal-package-${workspace.opportunityId || "proposal"}.zip"`,
      },
    });
  } catch (error) {
    console.error("Package generation error:", error);
    return NextResponse.json(
      { error: "Failed to generate package", details: error instanceof Error ? error.message : "Unknown error" },
      { status: 500 }
    );
  }
}

